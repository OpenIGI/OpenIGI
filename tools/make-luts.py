#!/usr/bin/env python3
"""Generates the colour grades in apps/OpenIGI.Desktop/Assets/luts.

A .cube file is 4096 lines of numbers; committing one with no record of where it came from makes the
grade unreviewable and unadjustable. This is that record. Run it after changing a look:

    python tools/make-luts.py

Every grade here is expressed in DISPLAY space, because that is where the renderer applies it -- after
the tone map and the sRGB encode, which is the space a colourist would have authored it in.

The per-mission looks are not invented from nothing: they follow the atmosphere already authored for
the same missions in Assets/fog-presets.json, so the grade and the fog are describing one weather
rather than two. Mission 1 is a cold clear morning over snow, 3 is overcast, 5 is a blue high-altitude
haze, 7 has the sun almost overhead.

SIZE. 16 rather than the industry-default 32. What a table has to resolve is the CURVATURE of the
grade between its samples, and every grade here is a smooth global operation -- a curve, a channel
balance, a saturation change -- with no key, no hue isolation and no hard break anywhere in it. 16
cubed is 4096 entries and about 90 KB; 32 cubed is eight times that to describe the same curve. The
loader reads whatever size a file declares, so an authored grade that needs more can simply say so.
"""

import os

SIZE = 16
OUT = os.path.join(os.path.dirname(__file__), "..", "apps", "OpenIGI.Desktop", "Assets", "luts")


def lerp(a, b, t):
    return a + (b - a) * t


def clamp01(x):
    return max(0.0, min(1.0, x))


def contrast(c, amount, pivot=0.5):
    """Pushes a channel away from a pivot. Above 1 is more contrast."""
    return (c - pivot) * amount + pivot


def lift_gamma_gain(c, lift, gamma, gain):
    """The colourist's three controls: shadows, midtones, highlights.

    Lift raises the floor without touching white, gain scales the ceiling without touching black, and
    gamma bends what is between them. Applied in this order because that is the order they compose in
    every grading tool, and a look authored elsewhere will not match if it is done differently.
    """
    c = lift + c * (1.0 - lift)
    c = clamp01(c) ** (1.0 / gamma) if gamma > 0 else c
    return c * gain


def saturate(rgb, amount):
    luma = 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]
    return tuple(lerp(luma, ch, amount) for ch in rgb)


def identity(rgb):
    return rgb


def mission1(rgb):
    """Cold clear morning over snow: blue in the shade, clean neutral highlights, crisp."""
    r, g, b = rgb
    # Lift the blue floor and hold the red one down -- that is what puts the cold in the SHADOWS
    # rather than over the whole picture, which is what a blanket blue tint would do to the snow.
    r = lift_gamma_gain(r, 0.000, 1.00, 0.99)
    g = lift_gamma_gain(g, 0.008, 1.01, 1.00)
    b = lift_gamma_gain(b, 0.030, 1.03, 1.01)
    r, g, b = (contrast(c, 1.06) for c in (r, g, b))
    return saturate((r, g, b), 0.96)


def mission3(rgb):
    """Overcast: flat, desaturated, lifted blacks. Haze is what removes contrast from a scene."""
    r, g, b = rgb
    r = lift_gamma_gain(r, 0.028, 1.00, 0.98)
    g = lift_gamma_gain(g, 0.030, 1.00, 0.99)
    b = lift_gamma_gain(b, 0.036, 1.00, 1.00)
    r, g, b = (contrast(c, 0.94) for c in (r, g, b))
    return saturate((r, g, b), 0.88)


def mission5(rgb):
    """Blue high-altitude haze: cool and CLEAN -- thin air is contrasty, unlike overcast."""
    r, g, b = rgb
    r = lift_gamma_gain(r, 0.000, 0.99, 0.98)
    g = lift_gamma_gain(g, 0.006, 1.00, 1.00)
    b = lift_gamma_gain(b, 0.024, 1.04, 1.03)
    r, g, b = (contrast(c, 1.10) for c in (r, g, b))
    return saturate((r, g, b), 1.02)


def mission7(rgb):
    """Sun almost overhead: warm, even, no strong direction to the light."""
    r, g, b = rgb
    r = lift_gamma_gain(r, 0.010, 1.02, 1.02)
    g = lift_gamma_gain(g, 0.006, 1.00, 1.00)
    b = lift_gamma_gain(b, 0.000, 0.98, 0.97)
    r, g, b = (contrast(c, 1.03) for c in (r, g, b))
    return saturate((r, g, b), 1.04)


GRADES = {
    "identity": (identity, "The grade that changes nothing. Sampling it is how the lookup's coordinate mapping is checked."),
    "mission1": (mission1, "Mission 1 -- cold clear morning over snow."),
    "mission3": (mission3, "Mission 3 -- overcast: flat and desaturated."),
    "mission5": (mission5, "Mission 5 -- blue high-altitude haze."),
    "mission7": (mission7, "Mission 7 -- sun almost overhead, warm and even."),
}


def write(name, grade, description):
    path = os.path.join(OUT, name + ".cube")
    step = 1.0 / (SIZE - 1)

    with open(path, "w", newline="\n") as f:
        f.write(f"# {description}\n")
        f.write("# Generated by tools/make-luts.py -- edit the generator, not this file.\n")
        f.write(f'TITLE "{name}"\n')
        f.write(f"LUT_3D_SIZE {SIZE}\n")

        # Red varies fastest, then green, then blue. That is the format's order and getting it wrong
        # produces a grade with its channels transposed, which reads as a wildly wrong look rather
        # than as a subtly wrong one -- so at least it fails loudly.
        for bi in range(SIZE):
            for gi in range(SIZE):
                for ri in range(SIZE):
                    out = grade((ri * step, gi * step, bi * step))
                    f.write(" ".join(f"{clamp01(c):.6f}" for c in out) + "\n")

    return path


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, (grade, description) in GRADES.items():
        print("wrote", os.path.relpath(write(name, grade, description)))


if __name__ == "__main__":
    main()
