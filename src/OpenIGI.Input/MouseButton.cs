namespace OpenIGI.Input;

/// <summary>A mouse button, numbered as DirectInput reports them.</summary>
public enum MouseButton
{
    /// <summary>The left button. Fire, and menu select.</summary>
    Left = 0,

    /// <summary>The right button. Aim down sights, and menu back.</summary>
    Right = 1,

    /// <summary>The middle button.</summary>
    Middle = 2,

    /// <summary>The first extra button.</summary>
    Extra1 = 3,

    /// <summary>The second extra button.</summary>
    Extra2 = 4,
}
