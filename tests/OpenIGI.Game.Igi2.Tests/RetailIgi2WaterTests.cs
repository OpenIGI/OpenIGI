using OpenIGI.Engine.Tasks;
using OpenIGI.Formats.Ilff;
using OpenIGI.Formats.Textures;
using OpenIGI.Game.Igi2.World;
using OpenIGI.TestSupport;
using Xunit;

namespace OpenIGI.Game.Igi2.Tests;

/// <summary>
/// <see cref="WaterTask"/> and its baked environment maps against every body of water the retail tree
/// ships.
/// </summary>
/// <remarks>
/// The face files are named from two things a task carries and nothing a file does: its level id and the
/// index list in <c>Resource list</c>. So, as with forests, the only proof both are read from the right
/// place is that the names the tasks generate are the names inside the archives.
/// </remarks>
public sealed class RetailIgi2WaterTests
{
    /// <summary>Every cube-map face a water task names is in the level's archive, and none is spare.</summary>
    /// <remarks>
    /// Checked in both directions across all 22 archives: every generated name resolves, and every entry
    /// in every archive is generated by some task. That is 186 files matched from two parameters and a
    /// task id, which a wrong reading of either would not survive.
    /// </remarks>
    [RequiresTitleDataFact("igi2")]
    public void Every_cube_map_face_is_named_by_a_water_task()
    {
        int sheets = 0;
        int faces = 0;
        int archives = 0;

        foreach (string script in RetailIgi2LevelLoadTests.LevelScripts())
        {
            string directory = Path.Combine(Path.GetDirectoryName(script)!, "envmaps");
            if (!Directory.Exists(directory))
            {
                continue;
            }

            RetailIgi2LevelLoadTests.Harness harness = new(script);
            harness.Loader.LoadScript(RetailIgi2LevelLoadTests.Harness.ScriptName);

            HashSet<string> onDisk = [];
            foreach (string path in Directory.EnumerateFiles(directory, "water_*.res"))
            {
                archives++;
                IresArchive archive = IresArchive.Read(File.ReadAllBytes(path));
                foreach (IresEntry entry in archive.Entries)
                {
                    onDisk.Add(FileNameOf(entry.Name));
                }
            }

            HashSet<string> named = [];
            foreach (WaterTask sheet in TasksOf<WaterTask>(harness.LevelRoot))
            {
                sheets++;
                foreach (int index in sheet.EnvmapIndices)
                {
                    for (int face = 0; face < WaterTask.CubeMapFaceCount; face++)
                    {
                        string resource = FileNameOf(sheet.CubeMapFaceResource(index, face));
                        faces++;

                        Assert.Contains(resource, onDisk);
                        named.Add(resource);
                    }
                }
            }

            Assert.Equal<string[]>(
                [.. onDisk.Order(StringComparer.Ordinal)],
                [.. named.Order(StringComparer.Ordinal)]);
        }

        Assert.Equal(22, archives);
        Assert.Equal(186, faces);
        Assert.True(sheets > 0, "No water was found.");
    }

    /// <summary>Every face decodes, and the six of a cube map agree on a square power-of-two size.</summary>
    /// <remarks>
    /// A cube texture is created once, at the width of face zero
    /// (<c>Envmap_LoadFromMemory</c>, <c>igi2ed 0x581670</c>), and the other five are loaded into it — so
    /// a face that disagreed would be silently rescaled by D3DX. Asserting they agree is what says the
    /// six really are one map.
    /// </remarks>
    [RequiresTitleDataFact("igi2")]
    public void The_six_faces_of_a_map_agree_on_one_square_size()
    {
        HashSet<int> sizes = [];

        foreach ((WaterTask sheet, IresArchive archive) in Sheets())
        {
            foreach (int index in sheet.EnvmapIndices)
            {
                int edge = -1;

                for (int face = 0; face < WaterTask.CubeMapFaceCount; face++)
                {
                    BitmapImage image = ReadFace(archive, sheet, index, face);

                    Assert.Equal(image.Width, image.Height);
                    Assert.True(
                        int.IsPow2(image.Width),
                        $"Face {face} of map {index} is {image.Width} across, which is not a power of two.");

                    if (edge < 0)
                    {
                        edge = image.Width;
                        sizes.Add(edge);
                    }

                    Assert.Equal(edge, image.Width);
                }
            }
        }

        Assert.Equal<int[]>([16, 64, 128, 256, 512], [.. sizes.Order()]);
    }

    /// <summary>
    /// A water task's environment-map resolution is a real resolution, and usually the one its faces
    /// were baked at.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <c>Envmap_Create</c> (<c>igi2ed 0x5817C0</c>) passes <c>Envmap_t::nResolution</c> straight to
    /// <c>Envmap_CubeMapRender</c> with no scaling, so the parameter is the edge length of the <i>next</i>
    /// bake rather than a description of what shipped. 23 of the 31 maps agree with their faces exactly;
    /// the other 8 are levels whose setting was changed after the bake, and they drift in both directions
    /// — five at half the baked size, two at a quarter, one at twice.
    /// </para>
    /// <para>
    /// So the claim is the weaker true one, and it is still enough to catch reading the parameter from
    /// the wrong slot: every declared value is a power of two inside the range the corpus bakes at.
    /// A neighbouring parameter would be a float, a colour component or a boolean, and none of those
    /// lands in that set.
    /// </para>
    /// </remarks>
    [RequiresTitleDataFact("igi2")]
    public void The_declared_resolution_is_a_resolution_and_usually_the_baked_one()
    {
        int maps = 0;
        int drifted = 0;

        foreach ((WaterTask sheet, IresArchive archive) in Sheets())
        {
            foreach (int index in sheet.EnvmapIndices)
            {
                maps++;

                Assert.True(
                    int.IsPow2(sheet.EnvmapResolution),
                    $"Water {sheet.Id} declares resolution {sheet.EnvmapResolution}, which is not a power of two.");
                Assert.InRange(sheet.EnvmapResolution, 16, 512);

                BitmapImage face = ReadFace(archive, sheet, index, 0);
                drifted += sheet.EnvmapResolution == face.Width ? 0 : 1;
            }
        }

        Assert.Equal(31, maps);
        Assert.Equal(8, drifted);
    }

    /// <summary>Every water that ships baked faces declares itself a cube map.</summary>
    /// <remarks>
    /// The alternative branch loads face zero alone into a flat texture, so a sheet shipping six faces
    /// and claiming not to be a cube map would waste five of them. None does.
    /// </remarks>
    [RequiresTitleDataFact("igi2")]
    public void Water_that_ships_faces_declares_itself_a_cube_map()
    {
        foreach ((WaterTask sheet, IresArchive _) in Sheets())
        {
            if (sheet.EnvmapIndices.Count > 0)
            {
                Assert.True(sheet.Cubemap, $"Water {sheet.Id} ships faces but is not a cube map.");
            }
        }
    }

    /// <summary>Every water sheet carries at least one wave train.</summary>
    /// <remarks>
    /// The surface is the sum of its <c>WaterLayer</c> children, so a sheet with none is flat. 19 levels
    /// declare both types; none declares a sheet without layers.
    /// </remarks>
    [RequiresTitleDataFact("igi2")]
    public void Every_sheet_carries_wave_layers()
    {
        int sheets = 0;
        int layers = 0;

        foreach (string script in RetailIgi2LevelLoadTests.LevelScripts())
        {
            RetailIgi2LevelLoadTests.Harness harness = new(script);
            harness.Loader.LoadScript(RetailIgi2LevelLoadTests.Harness.ScriptName);

            foreach (WaterTask sheet in TasksOf<WaterTask>(harness.LevelRoot))
            {
                sheets++;
                int own = TasksOf<WaterLayerTask>(sheet).Count();
                layers += own;

                Assert.True(own > 0, $"Water {sheet.Id} in '{script}' carries no wave layer.");
                Assert.True(sheet.Size > 0f, $"Water {sheet.Id} in '{script}' has no extent.");
            }
        }

        Assert.True(sheets > 0, "No water was found.");
        Assert.True(layers >= sheets, "Fewer layers than sheets.");
    }

    private static IEnumerable<(WaterTask Sheet, IresArchive Archive)> Sheets()
    {
        foreach (string script in RetailIgi2LevelLoadTests.LevelScripts())
        {
            string directory = Path.Combine(Path.GetDirectoryName(script)!, "envmaps");
            if (!Directory.Exists(directory))
            {
                continue;
            }

            RetailIgi2LevelLoadTests.Harness harness = new(script);
            harness.Loader.LoadScript(RetailIgi2LevelLoadTests.Harness.ScriptName);

            foreach (WaterTask sheet in TasksOf<WaterTask>(harness.LevelRoot))
            {
                string path = Path.Combine(directory, $"water_{sheet.Id}.res");
                if (File.Exists(path))
                {
                    yield return (sheet, IresArchive.Read(File.ReadAllBytes(path)));
                }
            }
        }
    }

    private static BitmapImage ReadFace(IresArchive archive, WaterTask sheet, int index, int face)
    {
        string wanted = FileNameOf(sheet.CubeMapFaceResource(index, face));
        IresEntry? entry = archive.Entries.FirstOrDefault(e => FileNameOf(e.Name) == wanted);

        Assert.True(entry is not null, $"'{wanted}' is not in the archive.");
        return BitmapImage.Read(entry!.Data.Span);
    }

    /// <summary>Reduces a resource name to the filename both sides can be compared on.</summary>
    /// <remarks>
    /// The water archives key their entries by a full <c>LOCAL:missions/…</c> path, unlike the heightmap
    /// archives, which use a bare name. That is the third of the three paths
    /// <c>Water_LoadEnvmapData</c> tries, so both keyings really do occur in shipped data — comparing on
    /// the filename is what lets this suite ignore a difference the virtual file system exists to absorb.
    /// </remarks>
    private static string FileNameOf(string resource) => resource[(resource.LastIndexOf('/') + 1)..];

    private static IEnumerable<T> TasksOf<T>(GameTask root)
        where T : GameTask
    {
        foreach (GameTask child in root.Children)
        {
            if (child is T match)
            {
                yield return match;
            }

            foreach (T nested in TasksOf<T>(child))
            {
                yield return nested;
            }
        }
    }
}
